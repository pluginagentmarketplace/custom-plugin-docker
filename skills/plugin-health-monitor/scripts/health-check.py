def run_health_check(plugin_path: str) -> Dict:
    """Run comprehensive health check"""
    path = Path(plugin_path)

    if not path.exists():
        return {"error": "Plugin path not found"}

    all_issues: List[HealthIssue] = []
    scores = HealthScore()

    # Run all checks
    scores.structure, structure_issues = check_structure(path)
    all_issues.extend(structure_issues)

    scores.syntax, syntax_issues = check_syntax(path)
    all_issues.extend(syntax_issues)

    scores.mcp, mcp_issues = check_mcp(path)
    all_issues.extend(mcp_issues)

    scores.loading, loading_issues = check_loading(path)
    all_issues.extend(loading_issues)

    scores.stability, stability_issues = check_stability(path)
    all_issues.extend(stability_issues)

    return {
        "plugin": path.name,
        "timestamp": datetime.now().isoformat(),
        "health_score": round(scores.total, 1),
        "status": scores.status,
        "component_scores": {
            "structure": scores.structure,
            "syntax": scores.syntax,
            "mcp": scores.mcp,
            "loading": scores.loading,
            "stability": scores.stability
        },
        "issues": [
            {
                "code": i.error_code,
                "severity": i.severity,
                "component": i.component,
                "message": i.message,
                "file": i.file_path,
                "auto_fixable": i.auto_fixable
            }
            for i in all_issues
        ],
        "issues_count": len(all_issues),
        "auto_fixable_count": sum(1 for i in all_issues if i.auto_fixable)
    }

def main():
    if len(sys.argv) < 2:
        print("Usage: python health-check.py <plugin_path>")
        sys.exit(1)

    result = run_health_check(sys.argv[1])

    if "error" in result:
        print(f"Error: {result['error']}")
        sys.exit(1)

    # Print report
    print("=" * 60)
    print(f"PLUGIN HEALTH REPORT: {result['plugin']}")
    print("=" * 60)
    print(f"\nOverall Score: {result['health_score']}/100 [{result['status']}]")
    print(f"\nComponent Scores:")
    for comp, score in result['component_scores'].items():
        status = "[OK]" if score >= 85 else "[WARN]" if score >= 70 else "[FAIL]"
        print(f"  {comp.capitalize():12} {score:5.1f}/100 {status}")

    if result['issues']:
        print(f"\nIssues Found: {result['issues_count']}")
        for issue in result['issues']:
            print(f"\n  [{issue['code']}] {issue['message']}")
            if issue['file']:
                print(f"    File: {issue['file']}")
            print(f"    Severity: {issue['severity']}")
            print(f"    Auto-fixable: {'Yes' if issue['auto_fixable'] else 'No'}")
    else:
        print("\nNo issues detected!")

    print("\n" + "=" * 60)

    # Exit with appropriate code
    sys.exit(0 if result['status'] == 'HEALTHY' else 1)

if __name__ == "__main__":
    main()
